const SITE = 'https://www.learnmathclass.com'

// Hub is released separately from its leaves; flip to true once it meets the release criteria.
const HUB_INDEXED = false

export async function getStaticProps() {
  const url = complexNumbersMethods.hubPath

  const seoData = {
    title: "Complex Number Methods: Divide, Polar Form, De Moivre, Roots | Learn Math Class",
    description:
      "Every complex-number how-to on one page: arithmetic, division, polar and exponential forms, De Moivre powers, nth roots, polynomial roots and plotting.",
    keywords: ["complex number methods","how to divide complex numbers","convert to polar form","de moivre theorem steps","nth roots of complex numbers","complex roots of polynomials"].join(', '),
    url,
    robots: HUB_INDEXED ? 'index, follow' : 'noindex, follow',
  }

  const schemas = {
    learningResource: {
      '@context': 'https://schema.org',
      '@type': 'LearningResource',
      name: 'Complex Number Methods',
      description: seoData.description,
      url: `${SITE}${url}`,
      educationalLevel: 'High School, College',
      learningResourceType: 'Methods collection',
      about: { '@type': 'Thing', name: 'Complex numbers' },
      inLanguage: 'en',
    },
    breadcrumb: {
      '@context': 'https://schema.org',
      '@type': 'BreadcrumbList',
      itemListElement: [
        { '@type': 'ListItem', position: 1, name: 'Home', item: SITE },
        { '@type': 'ListItem', position: 2, name: 'Complex numbers', item: `${SITE}/complex-numbers` },
        { '@type': 'ListItem', position: 3, name: 'Methods', item: `${SITE}${url}` },
      ],
    },
  }

  return { props: { seoData, schemas } }
}

